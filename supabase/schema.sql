CREATE TABLE IF NOT EXISTS public.reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  city TEXT DEFAULT 'Verified Traveler',
  rating INTEGER NOT NULL DEFAULT 5,
  review TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

ALTER TABLE public.reviews ADD COLUMN IF NOT EXISTS location TEXT;
ALTER TABLE public.reviews ADD COLUMN IF NOT EXISTS comment TEXT;
ALTER TABLE public.reviews ADD COLUMN IF NOT EXISTS user_name TEXT;
ALTER TABLE public.reviews ADD COLUMN IF NOT EXISTS review_text TEXT;
ALTER TABLE public.reviews ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now());

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'reviews_rating_range') THEN
    ALTER TABLE public.reviews ADD CONSTRAINT reviews_rating_range CHECK (rating >= 1 AND rating <= 5);
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'reviews_name_length') THEN
    ALTER TABLE public.reviews ADD CONSTRAINT reviews_name_length CHECK (char_length(trim(name)) >= 2 AND char_length(name) <= 100);
  END IF;

  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'reviews_review_length') THEN
    ALTER TABLE public.reviews ADD CONSTRAINT reviews_review_length CHECK (char_length(trim(review)) >= 10 AND char_length(review) <= 2000);
  END IF;
END $$;

CREATE OR REPLACE FUNCTION public.handle_review_defaults_and_sync()
RETURNS TRIGGER AS $$
BEGIN
  NEW.created_at := COALESCE(NEW.created_at, timezone('utc'::text, now()));
  NEW.updated_at := timezone('utc'::text, now());

  IF (NEW.city IS NULL OR trim(NEW.city) = '') AND (NEW.location IS NOT NULL AND trim(NEW.location) <> '') THEN
    NEW.city := trim(NEW.location);
  ELSIF (NEW.location IS NULL OR trim(NEW.location) = '') AND (NEW.city IS NOT NULL AND trim(NEW.city) <> '') THEN
    NEW.location := trim(NEW.city);
  ELSIF (NEW.city IS NULL OR trim(NEW.city) = '') THEN
    NEW.city := 'Verified Traveler';
    NEW.location := 'Verified Traveler';
  END IF;

  IF (NEW.review IS NULL OR trim(NEW.review) = '') AND (NEW.comment IS NOT NULL AND trim(NEW.comment) <> '') THEN
    NEW.review := trim(NEW.comment);
  ELSIF (NEW.review IS NULL OR trim(NEW.review) = '') AND (NEW.review_text IS NOT NULL AND trim(NEW.review_text) <> '') THEN
    NEW.review := trim(NEW.review_text);
  END IF;
  NEW.comment := NEW.review;
  NEW.review_text := NEW.review;

  IF (NEW.name IS NULL OR trim(NEW.name) = '') AND (NEW.user_name IS NOT NULL AND trim(NEW.user_name) <> '') THEN
    NEW.name := trim(NEW.user_name);
  END IF;
  NEW.user_name := NEW.name;

  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_sync_review_fields ON public.reviews;
CREATE TRIGGER trg_sync_review_fields
  BEFORE INSERT OR UPDATE ON public.reviews
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_review_defaults_and_sync();

CREATE INDEX IF NOT EXISTS idx_reviews_created_at ON public.reviews (created_at DESC);

ALTER TABLE public.reviews ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.reviews FROM PUBLIC;
GRANT SELECT, INSERT ON public.reviews TO anon, authenticated;

DO $$
BEGIN
  EXECUTE 'GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated';
EXCEPTION WHEN OTHERS THEN
  NULL;
END $$;

DROP POLICY IF EXISTS "Allow public read access to reviews" ON public.reviews;
CREATE POLICY "Allow public read access to reviews"
  ON public.reviews
  FOR SELECT
  TO public
  USING (true);

DROP POLICY IF EXISTS "Allow public insert access to reviews" ON public.reviews;
CREATE POLICY "Allow public insert access to reviews"
  ON public.reviews
  FOR INSERT
  TO anon, authenticated
  WITH CHECK (
    char_length(trim(name)) >= 2 AND
    char_length(name) <= 100 AND
    rating >= 1 AND
    rating <= 5 AND
    char_length(trim(review)) >= 10 AND
    char_length(review) <= 2000
  );

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' 
    AND schemaname = 'public' 
    AND tablename = 'reviews'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.reviews;
  END IF;
END $$;
